/**
 * Returns the display label for a stored canonical state value.
 * In Hindi mode returns the Hindi name; in English mode returns the English name.
 */
export function displayState(state, lang) {
  if (!state) return "";
  if (lang === "hi") return STATE_HINDI[state] || state;
  return state;
}

export function useT(lang) {
  return (key, vars = {}) => {
    let str = translations[lang]?.[key] || translations.en[key] || key;
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replace(`{${k}}`, v);
    });
    return str;
  };
}
